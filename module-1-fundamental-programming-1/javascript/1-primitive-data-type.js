/* 
@@@@@@@@@@@@@@@@@@ Primitive Data Types @@@@@@@@@@@@@@@@@@
*/

// String
let name = "Alice";
console.log("Name:", name);  // "Alice"

// Number (Integer)
let age = 25;
console.log("Age:", age);  // 25

// Decimal (Floating-point Number)
let price = 19.99;
console.log("Price:", price);  // 19.99

// Boolean
let isStudent = true;
console.log("Is Student:", isStudent);  // true

// Undefined
let address;
console.log("Address:", address);  // undefined

// Null
let user = null;
console.log("User:", user);  // null

/*
    Undefined vs Null
    In JavaScript, undefined means a variable has been declared but not assigned a value,
    while null represents an intentional assignment of "no value" or the absence of any object.
*/
